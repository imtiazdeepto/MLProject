def histogram(df,col_name):
  plt.figure(figsize=(5, 3))
  sns.histplot(df[col_name],kde=True)
  plt.xlabel(col_name)
  plt.ylabel('Frequency')
  plt.title(f'Histogram of {col_name}')
  _mean=df[col_name].mean()
  _median=df[col_name].median()
  plt.axvline(_mean,color='red',linestyle='dashed',linewidth=1,label='mean')
  plt.axvline(_median,color='green',linestyle='dotted',linewidth=1,label='median')
  plt.legend()
  plt.show()

  rel_diff = abs(_mean - _median) / _mean if _mean != 0 else 0

  if rel_diff < 0.05:
        assessment = "Symmetric enough"
  elif rel_diff < 0.20:
        assessment = "Moderately skewed - consider transform"
  else:
        assessment = "Highly skewed - must transform"

  print(f"\nColumn: {col_name}")
  print(f"Mean: {_mean:.4f}")
  print(f"Median: {_median:.4f}")
  print(f"Relative Difference: {rel_diff:.4f} ({rel_diff:.2%})")
  print(f"Assessment: {assessment}")

