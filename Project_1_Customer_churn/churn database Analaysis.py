def boxplot(df, col_name):

    plt.figure(figsize=(6, 4))

    # 1. Boxplot আঁকা
    sns.boxplot(x=df[col_name], color='skyblue', width=0.4)

    # 2. Title আর লেবেল
    plt.title(f'Boxplot of {col_name}')
    plt.xlabel(col_name)

    # 3. Mean (লাল) আর Median (সবুজ) লাইন
    _mean = df[col_name].mean()
    _median = df[col_name].median()

    plt.axvline(_mean, color='red', linestyle='--', linewidth=1.5, label=f'Mean: {_mean:.2f}')
    plt.axvline(_median, color='green', linestyle=':', linewidth=1.5, label=f'Median: {_median:.2f}')

    plt.legend()
    plt.tight_layout()
    plt.show()

    # 4. পরিসংখ্যান (Statistics) বের করা
    q1 = df[col_name].quantile(0.25)
    q3 = df[col_name].quantile(0.75)
    iqr = q3 - q1
    lower_fence = q1 - 1.5 * iqr
    upper_fence = q3 + 1.5 * iqr

    # Outlier সংখ্যা
    outliers = df[(df[col_name] < lower_fence) | (df[col_name] > upper_fence)][col_name]
    outlier_count = len(outliers)
    outlier_pct = (outlier_count / len(df)) * 100

    # Skewness (Mean vs Median)
    rel_diff = abs(_mean - _median) / _mean if _mean != 0 else 0

    # 5. কনসোলে কমেন্ট প্রিন্ট
    print(f"\n{'='*50}")
    print(f"📊 BOXPLT ANALYSIS: {col_name}")
    print(f"{'='*50}")
    print(f"Mean      : {_mean:.4f}")
    print(f"Median    : {_median:.4f}")
    print(f"Q1 (25%)  : {q1:.4f}")
    print(f"Q3 (75%)  : {q3:.4f}")
    print(f"IQR       : {iqr:.4f}")
    print(f"Lower Fence: {lower_fence:.4f}")
    print(f"Upper Fence: {upper_fence:.4f}")
    print(f"Outliers  : {outlier_count} ({outlier_pct:.2f}%)")
    print(f"Rel. Diff : {rel_diff:.4f} ({rel_diff:.2%})")
    print(f"{'='*50}")

    # 6. Interpretation / Comment
    comments = []

    # Skewness comment
    if _mean > _median:
        comments.append("📌 Right-skewed: Mean > Median (লেজ ডানদিকে লম্বা)")
    elif _mean < _median:
        comments.append("📌 Left-skewed: Mean < Median (লেজ বামদিকে লম্বা)")
    else:
        comments.append("✅ Symmetric: Mean ≈ Median")

    # Outlier comment
    if outlier_pct == 0:
        comments.append("✅ কোনো Outlier নেই।")
    elif outlier_pct < 1:
        comments.append(f"⚠️ অল্প কিছু Outlier আছে ({outlier_pct:.2f}%) — সমস্যা না।")
    elif outlier_pct < 5:
        comments.append(f"⚠️ Moderate Outliers ({outlier_pct:.2f}%) — Transform বা Capping ভাবতে পারেন।")
    else:
        comments.append(f"🔴 Heavy Outliers ({outlier_pct:.2f}%) — Robust Scaler / Log Transform মাস্ট!")

    # IQR vs Range comment
    data_range = df[col_name].max() - df[col_name].min()
    if iqr / data_range < 0.3:
        comments.append("🔴 Data অনেক ছড়ানো (Spread out) — Variance বেশি।")
    else:
        comments.append("✅ Data ভালোভাবে কনসেনট্রেটেড (Compact)।")

    # Print all comments
    print("\n💬 COMMENTS:")
    for c in comments:
        print(f"   {c}")
    print(f"{'='*50}\n")

